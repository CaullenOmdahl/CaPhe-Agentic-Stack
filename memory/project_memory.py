#!/usr/bin/env python3
"""Git-stored project memory shared by every agent.

Canonical memory is plain Markdown in the project's own repository at
`.agent/memory/`: one fact per file plus a generated `MEMORY.md` index.
Memory that cannot live in a private project repository (public repositories,
non-Git folders, deleted projects, cross-project owner facts) lives in a private
hub repository, `$CAPHE_MEMORY_HUB` (default `~/agent-memory`), under
`projects/<name>/` and `global/`.

    caphe-memory list [PATH] [--full]   stores that apply to PATH, innermost first
    caphe-memory search TERM... [--path PATH] [--all]
                                        search every store that applies, parents and hub included
    caphe-memory where [PATH]           the store new memories for PATH belong in
    caphe-memory new TYPE NAME DESC [--path PATH] [--source AGENT]
    caphe-memory check [--fail-on-secrets] [STORE ...]
                                        schema and index freshness; secrets are warnings unless
                                        --fail-on-secrets (use it for any public repository)
    caphe-memory index [STORE ...]      regenerate MEMORY.md
    caphe-memory import-claude SRC DEST
    caphe-memory import-codex CODEX_HOME
    caphe-memory link-claude REPO [--claude-home DIR]

Stores are read-only for this tool except `new`, `index`, and the importers.
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import importlib.util
import json
import os
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, Iterable

STORE_REL = Path(".agent") / "memory"
INDEX = "MEMORY.md"
TYPES = ("user", "feedback", "project", "reference", "session")
STATUSES = ("active", "superseded")
REQUIRED = ("name", "description", "type")
# Recommended so agents without the canonical template (e.g. a client's native writer) still pass.
RECOMMENDED = ("created", "updated", "source", "status")
KEY_ORDER = (*REQUIRED, *RECOMMENDED, "supersedes")
DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
INDEX_HEADER = (
    "# Memory Index\n\n"
    "<!-- Generated by `caphe-memory index`; edit the memory files, not this index. -->\n"
)


class StoreError(RuntimeError):
    """A store failed validation and cannot be indexed."""


@dataclass
class Memory:
    path: Path
    meta: dict[str, str]
    body: str

    def __getattr__(self, key: str) -> str:
        try:
            return self.meta[key]
        except KeyError as exc:
            raise AttributeError(key) from exc


@dataclass
class Problem:
    path: Path
    line: int
    message: str
    severity: str = "error"  # error | warning

    def __str__(self) -> str:
        return f"{self.path}:{self.line}: {self.severity}: {self.message}"


def errors(problems: list[Problem]) -> list[Problem]:
    return [p for p in problems if p.severity == "error"]


@dataclass
class Store:
    root: Path
    kind: str  # repo | hub-project | hub-global
    label: str = ""


@dataclass
class Hub:
    root: Path
    projects: dict[str, str] = field(default_factory=dict)
    overrides: list[dict[str, str]] = field(default_factory=list)

    @classmethod
    def load(cls, root: Path | None = None) -> "Hub":
        root = Path(root or os.environ.get("CAPHE_MEMORY_HUB", Path.home() / "agent-memory"))
        mapping = root / "projects.json"
        data = json.loads(mapping.read_text()) if mapping.is_file() else {}
        return cls(root, data.get("paths", {}), data.get("subject_overrides", []))

    def project_store(self, name: str) -> Store:
        return Store(self.root / "projects" / name, "hub-project", name)

    def global_store(self) -> Store:
        return Store(self.root / "global", "hub-global", "global")


# ------------------------------------------------------------------ format


def _secret_patterns() -> tuple:
    """Reuse the sanitizer's patterns so memory and MemPalace agree on secrets."""
    path = Path(__file__).with_name("mempalace_adapter.py")
    spec = importlib.util.spec_from_file_location("_caphe_mempalace_adapter", path)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    sys.modules.setdefault(spec.name, module)
    spec.loader.exec_module(module)
    return module.SECRET_PATTERNS


SECRET_PATTERNS = _secret_patterns()


def split_frontmatter(text: str) -> tuple[dict[str, str], str, int]:
    """Return (flat metadata, body, body start line). Nested `metadata:` keys are flattened."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return {}, text, 1
    meta: dict[str, str] = {}
    for n, line in enumerate(lines[1:], start=2):
        if line.strip() == "---":
            return meta, "\n".join(lines[n:]).lstrip("\n"), n + 1
        m = re.match(r"^\s*([A-Za-z_][\w-]*):\s*(.*)$", line)
        if m and m.group(2) != "":
            meta[m.group(1)] = m.group(2).strip().strip('"').strip("'")
    return {}, text, 1


def parse_memory(path: Path) -> Memory:
    meta, body, _ = split_frontmatter(path.read_text(encoding="utf-8", errors="replace"))
    return Memory(path, meta, body)


def render_memory(meta: dict[str, str], body: str) -> str:
    keys = [k for k in KEY_ORDER if k in meta] + [k for k in meta if k not in KEY_ORDER]
    head = "\n".join(f"{k}: {meta[k]}" for k in keys)
    return f"---\n{head}\n---\n\n{body.strip()}\n"


def memory_files(store: Path) -> list[Path]:
    if not store.is_dir():
        return []
    return sorted(p for p in store.glob("*.md") if p.name != INDEX)


def scan_secrets(path: Path) -> list[Problem]:
    problems = []
    text = path.read_text(encoding="utf-8", errors="replace")
    for label, pattern in SECRET_PATTERNS:
        for m in pattern.finditer(text):
            line = text.count("\n", 0, m.start()) + 1
            # Private stores may keep credentials that would otherwise be lost; public ones must not.
            problems.append(Problem(path, line, f"secret: {label} value present; keep this store private",
                                    "warning"))
    return problems


def check_file(path: Path) -> list[Problem]:
    problems: list[Problem] = []
    mem = parse_memory(path)
    if not mem.meta:
        return [Problem(path, 1, "missing frontmatter")]
    for key in REQUIRED:
        if not mem.meta.get(key):
            problems.append(Problem(path, 1, f"missing required field: {key}"))
    for key in RECOMMENDED:
        if not mem.meta.get(key):
            problems.append(Problem(path, 1, f"missing recommended field: {key}", "warning"))
    if mem.meta.get("type") and mem.meta["type"] not in TYPES:
        problems.append(Problem(path, 1, f"type must be one of {', '.join(TYPES)}"))
    if mem.meta.get("status") and mem.meta["status"] not in STATUSES:
        problems.append(Problem(path, 1, f"status must be one of {', '.join(STATUSES)}"))
    for key in ("created", "updated"):
        if mem.meta.get(key) and not DATE.match(mem.meta[key]):
            problems.append(Problem(path, 1, f"{key} must be YYYY-MM-DD"))
    if not mem.body.strip():
        problems.append(Problem(path, 1, "empty body"))
    return problems + scan_secrets(path)


def check_store(store: Path, *, include_index: bool = True) -> list[Problem]:
    problems = [p for f in memory_files(store) for p in check_file(f)]
    if include_index and not errors(problems):
        index = store / INDEX
        current = index.read_text(encoding="utf-8") if index.is_file() else None
        if current != render_index(store):
            problems.append(Problem(index, 1, "index is stale; run `caphe-memory index`", "warning"))
    return problems


def render_index(store: Path) -> str:
    rows = []
    for f in memory_files(store):
        mem = parse_memory(f)
        if mem.meta.get("status", "active") != "active":
            continue
        rows.append((TYPES.index(mem.meta["type"]) if mem.meta.get("type") in TYPES else 99,
                     f.name, f"- [{mem.meta.get('name', f.stem)}]({f.name}) — {mem.meta.get('description', '')}"))
    rows.sort()
    return INDEX_HEADER + ("\n" + "\n".join(r[2] for r in rows) + "\n" if rows else "")


def write_index(store: Path) -> Path:
    problems = errors(check_store(store, include_index=False))
    if problems:
        raise StoreError("\n".join(map(str, problems)))
    store.mkdir(parents=True, exist_ok=True)
    index = store / INDEX
    index.write_text(render_index(store), encoding="utf-8")
    return index


def slugify(text: str, limit: int = 60) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return slug[:limit].rstrip("-") or "memory"


def today() -> str:
    return dt.date.today().isoformat()


# ------------------------------------------------------------------ discovery


def git_toplevel(path: Path) -> Path | None:
    try:
        out = subprocess.run(["git", "-C", str(path), "rev-parse", "--show-toplevel"],
                             capture_output=True, text=True, timeout=10)
    except (OSError, subprocess.TimeoutExpired):
        return None
    return Path(out.stdout.strip()) if out.returncode == 0 and out.stdout.strip() else None


def enclosing_repos(path: Path) -> list[Path]:
    """Every Git repository root containing PATH, innermost first (nested repos included)."""
    roots: list[Path] = []
    probe = path
    while True:
        top = git_toplevel(probe)
        if top is None:
            break
        if top not in roots:
            roots.append(top)
        if top.parent == top:
            break
        probe = top.parent
    return roots


def hub_store_for(path: Path, hub: Hub) -> Store | None:
    """The hub store a path inside the hub checkout belongs to; None when outside the hub."""
    root = hub.root.resolve()
    if path != root and root not in path.parents:
        return None
    projects = root / "projects"
    if projects in path.parents:
        # Nearest indexed folder (entries may nest, e.g. projects/group/name); else the top folder.
        probe = path
        while probe.parent != projects:
            if (probe / INDEX).is_file():
                break
            probe = probe.parent
        return hub.project_store(str(probe.relative_to(projects)))
    return hub.global_store()


def hub_project_for(path: Path, hub: Hub) -> str | None:
    for p in [path, *path.parents]:
        name = hub.projects.get(str(p))
        if name:
            return name
    return None


def stores_for(path: Path, hub: Hub) -> list[Store]:
    path = path.resolve()
    inside = hub_store_for(path, hub)
    if inside is not None:
        return [s for s in (inside, hub.global_store()) if s.root.is_dir()][:1 if inside.kind == "hub-global" else 2]
    stores: list[Store] = []
    for repo in enclosing_repos(path):
        store = repo / STORE_REL
        if store.is_dir():
            stores.append(Store(store, "repo", repo.name))
    name = hub_project_for(path, hub)
    if name and hub.project_store(name).root.is_dir():
        stores.append(hub.project_store(name))
    if hub.global_store().root.is_dir():
        stores.append(hub.global_store())
    return stores


@dataclass
class Hit:
    path: Path
    store: Store
    memory: Memory
    score: int


def search(path: Path, terms: list[str], hub: Hub, include_superseded: bool = False) -> list[Hit]:
    """Memories in every applicable store containing all TERMS; name/description matches rank first."""
    # Agents often quote a whole phrase; treat it as its words, all of which must match.
    terms = [w.lower() for t in terms for w in t.split()]
    hits = []
    for order, store in enumerate(stores_for(path, hub)):
        for f in memory_files(store.root):
            mem = parse_memory(f)
            if not include_superseded and mem.meta.get("status", "active") != "active":
                continue
            head = f"{mem.meta.get('name', '')} {mem.meta.get('description', '')} {f.stem}".lower()
            text = head + " " + mem.body.lower()
            if terms and all(t in text for t in terms):
                score = sum(2 if t in head else 1 for t in terms)
                hits.append((-score, order, f.name, Hit(f, store, mem, score)))
    return [h[-1] for h in sorted(hits, key=lambda h: h[:3])]


def write_target(path: Path, hub: Hub) -> Store:
    """Hub mapping wins (public, non-Git, local-only); otherwise the innermost repo."""
    path = path.resolve()
    inside = hub_store_for(path, hub)
    if inside is not None:
        return inside
    name = hub_project_for(path, hub)
    if name:
        return hub.project_store(name)
    repos = enclosing_repos(path)
    if repos:
        return Store(repos[0] / STORE_REL, "repo", repos[0].name)
    return hub.project_store(path.name)


# ------------------------------------------------------------------ importers


def _body_hash(body: str) -> str:
    return hashlib.sha256(body.strip().encode()).hexdigest()[:12]


def _existing_hashes(store: Path) -> set[str]:
    hashes = set()
    for f in memory_files(store):
        m = re.search(r"#([0-9a-f]{12})\b", parse_memory(f).meta.get("source", ""))
        if m:
            hashes.add(m.group(1))
    return hashes


def _write_new(store: Path, stem: str, meta: dict[str, str], body: str) -> Path | None:
    """Write a memory unless an identical body was already imported. Never overwrites."""
    store.mkdir(parents=True, exist_ok=True)
    if _body_hash(body) in _existing_hashes(store):
        return None
    target = store / f"{stem}.md"
    n = 2
    while target.exists():
        target = store / f"{stem}-{n}.md"
        n += 1
    target.write_text(render_memory(meta, body), encoding="utf-8")
    return target


def import_claude(src: Path, dest: Path) -> list[Path]:
    """Convert a Claude auto-memory directory into canonical files in DEST."""
    written = []
    for f in memory_files(src):
        mem = parse_memory(f)
        kind = mem.meta.get("type") if mem.meta.get("type") in TYPES else "project"
        date = dt.date.fromtimestamp(f.stat().st_mtime).isoformat()
        body = mem.body if mem.meta else f.read_text(encoding="utf-8", errors="replace")
        meta = {
            "name": mem.meta.get("name", f.stem.replace("_", " ")),
            "description": mem.meta.get("description", "").replace("\n", " ") or f.stem,
            "type": kind, "created": date, "updated": date,
            "source": f"claude import #{_body_hash(body)}", "status": "active",
        }
        stem = f.stem if f.stem.startswith(f"{kind}_") else f"{kind}_{slugify(f.stem)}"
        out = _write_new(dest, stem, meta, body)
        if out:
            written.append(out)
    return written


def parse_codex_task_groups(handbook: str) -> list[tuple[str, str, str]]:
    """(heading, description, section text) for each `# Task Group:` section."""
    parts = re.split(r"(?m)^# Task Group:\s*", handbook)[1:]
    out = []
    for part in parts:
        heading, _, rest = part.partition("\n")
        scope = re.search(r"(?m)^scope:\s*(.+)$", rest)
        out.append((heading.strip(), scope.group(1).strip() if scope else heading.strip(), rest.strip()))
    return out


def codex_paths(text: str) -> list[str]:
    home = str(Path.home())
    return [m.rstrip(".,;:)") for m in re.findall(re.escape(home) + r"/[^\s`'\"]+", text)]


def import_codex(codex_home: Path, route: Callable[[str, str], Path | None]) -> list[Path]:
    """Import Codex task groups and rollout summaries; ROUTE(path, subject) picks the store."""
    written: list[Path] = []
    mem_dir = codex_home / "memories"
    handbook = mem_dir / "MEMORY.md"
    if handbook.is_file():
        for heading, desc, section in parse_codex_task_groups(handbook.read_text(errors="replace")):
            paths = codex_paths(heading) or codex_paths(section[:400])
            store = route(paths[0] if paths else "", heading)
            if store is None:
                continue
            title = heading.split(" ", 1)[1] if paths and " " in heading else heading
            body = f"# {title}\n\n{section}"
            meta = {"name": title, "description": desc, "type": "project",
                    "created": today(), "updated": today(),
                    "source": f"codex task-group #{_body_hash(body)}", "status": "active"}
            out = _write_new(store, f"project_codex-{slugify(title)}", meta, body)
            if out:
                written.append(out)
    for f in sorted((mem_dir / "rollout_summaries").glob("*.md")):
        text = f.read_text(errors="replace")
        cwd = re.search(r"(?m)^cwd:\s*(\S.*)$", text[:1500])
        title = re.search(r"(?m)^# (.+)$", text)
        store = route(cwd.group(1).strip() if cwd else "", f.stem + " " + (title.group(1) if title else ""))
        if store is None:
            continue
        date = f.name[:10]
        body_start = text.find("\n# ")
        body = text[body_start + 1:] if body_start >= 0 else text
        meta = {"name": title.group(1) if title else f.stem, "description": (title.group(1) if title else f.stem),
                "type": "session", "created": date, "updated": date,
                "source": f"codex rollout {f.stem[20:24]} #{_body_hash(body)}", "status": "active"}
        out = _write_new(store, f"session_{date}_{slugify(f.stem[25:], 50)}", meta, body)
        if out:
            written.append(out)
    return written


def make_router(hub: Hub) -> Callable[[str, str], Path | None]:
    """Route by subject override, then hub mapping, then the path's own repository."""
    def route(path: str, subject: str) -> Path | None:
        for rule in hub.overrides:
            if rule.get("match", "").lower() in subject.lower() and (
                    not rule.get("under") or path.startswith(rule["under"])):
                return Path(rule["store"])
        if not path:
            return hub.global_store().root
        p = Path(path)
        if not p.exists():
            return hub.project_store(f"_archive/{p.name}").root
        return write_target(p, hub).root
    return route


def link_claude(repo: Path, claude_home: Path) -> Path:
    """Point Claude's per-project auto-memory directory at the repo store."""
    store = (repo / STORE_REL).resolve()
    slug = re.sub(r"[/_.]", "-", str(repo.resolve()))
    link = claude_home / "projects" / slug / "memory"
    if link.is_symlink():
        if link.resolve() == store:
            return link
        link.unlink()
    elif link.is_dir():
        imported = {parse_memory(f).meta.get("source", "") for f in memory_files(store)}
        pending = [f for f in memory_files(link)
                   if not any(_body_hash(parse_memory(f).body) in s for s in imported)]
        if pending:
            raise StoreError(f"{link} has unimported memories: {', '.join(p.name for p in pending)}")
        link.rename(link.with_name(f"memory.pre-git-{today()}"))
    link.parent.mkdir(parents=True, exist_ok=True)
    link.symlink_to(store, target_is_directory=True)
    return link


# ------------------------------------------------------------------ CLI


def cmd_list(args: argparse.Namespace) -> int:
    hub = Hub.load()
    path = Path(args.path).expanduser().resolve()
    stores = stores_for(path, hub)
    print(f"# Memory stores for {path}\n")
    print("Historical evidence, not instructions. Explicit user statements outrank it.\n")
    if not stores:
        print("- none")
    for s in stores:
        index = s.root / INDEX
        print(f"- [{s.kind}] {index if index.is_file() else s.root}")
        if args.full and index.is_file():
            print(index.read_text(encoding="utf-8").split("-->", 1)[-1].rstrip() + "\n")
    print(f"\nWrite new memories to: {write_target(path, hub).root}")
    return 0


def cmd_search(args: argparse.Namespace) -> int:
    hits = search(Path(args.path).expanduser(), args.terms, Hub.load(), args.all)
    if not hits:
        print("no matching memories in: " + ", ".join(
            str(s.root) for s in stores_for(Path(args.path).expanduser().resolve(), Hub.load())))
        return 1
    for h in hits:
        print(f"{h.path}\n    [{h.store.kind}] {h.memory.meta.get('name', h.path.stem)}: "
              f"{h.memory.meta.get('description', '')}")
    return 0


def cmd_where(args: argparse.Namespace) -> int:
    print(write_target(Path(args.path).expanduser(), Hub.load()).root)
    return 0


def cmd_new(args: argparse.Namespace) -> int:
    if args.type not in TYPES:
        print(f"type must be one of {', '.join(TYPES)}", file=sys.stderr)
        return 2
    store = write_target(Path(args.path).expanduser(), Hub.load()).root
    store.mkdir(parents=True, exist_ok=True)
    target = store / f"{args.type}_{slugify(args.name)}.md"
    if target.exists():
        print(f"exists; update it instead: {target}", file=sys.stderr)
        return 1
    meta = {"name": args.name, "description": args.description, "type": args.type,
            "created": today(), "updated": today(), "source": args.source, "status": "active"}
    target.write_text(render_memory(meta, args.body or "Replace with the fact, then **Why:** and **How to apply:**."),
                      encoding="utf-8")
    print(target)
    return 0


def _stores_arg(values: Iterable[str]) -> list[Path]:
    paths = [Path(v).expanduser() for v in values] or [Path.cwd()]
    hub = Hub.load()
    out = []
    for p in paths:
        out.append(p if (p.name == "memory" or (p / INDEX).exists() or p.parent.name == "projects")
                   else write_target(p, hub).root)
    return out


def cmd_check(args: argparse.Namespace) -> int:
    problems = [p for s in _stores_arg(args.stores) for p in check_store(s)]
    for p in problems:
        print(p)
    if args.fail_on_secrets:
        return 1 if problems else 0
    return 1 if errors(problems) else 0


def cmd_index(args: argparse.Namespace) -> int:
    for s in _stores_arg(args.stores):
        try:
            print(write_index(s))
        except StoreError as exc:
            print(exc, file=sys.stderr)
            return 1
    return 0


def cmd_import_claude(args: argparse.Namespace) -> int:
    for p in import_claude(Path(args.src).expanduser(), Path(args.dest).expanduser()):
        print(p)
    return 0


def cmd_import_codex(args: argparse.Namespace) -> int:
    for p in import_codex(Path(args.codex_home).expanduser(), make_router(Hub.load())):
        print(p)
    return 0


def cmd_link_claude(args: argparse.Namespace) -> int:
    try:
        print(link_claude(Path(args.repo).expanduser(), Path(args.claude_home).expanduser()))
    except StoreError as exc:
        print(exc, file=sys.stderr)
        return 1
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="caphe-memory", description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("list"); p.add_argument("path", nargs="?", default="."); p.add_argument("--full", action="store_true"); p.set_defaults(fn=cmd_list)
    p = sub.add_parser("search"); p.add_argument("terms", nargs="+"); p.add_argument("--path", default="."); p.add_argument("--all", action="store_true"); p.set_defaults(fn=cmd_search)
    p = sub.add_parser("where"); p.add_argument("path", nargs="?", default="."); p.set_defaults(fn=cmd_where)
    p = sub.add_parser("new"); p.add_argument("type"); p.add_argument("name"); p.add_argument("description")
    p.add_argument("--path", default="."); p.add_argument("--source", default="owner"); p.add_argument("--body"); p.set_defaults(fn=cmd_new)
    p = sub.add_parser("check"); p.add_argument("stores", nargs="*"); p.add_argument("--fail-on-secrets", action="store_true"); p.set_defaults(fn=cmd_check)
    p = sub.add_parser("index"); p.add_argument("stores", nargs="*"); p.set_defaults(fn=cmd_index)
    p = sub.add_parser("import-claude"); p.add_argument("src"); p.add_argument("dest"); p.set_defaults(fn=cmd_import_claude)
    p = sub.add_parser("import-codex"); p.add_argument("codex_home", nargs="?", default=str(Path.home() / ".codex")); p.set_defaults(fn=cmd_import_codex)
    p = sub.add_parser("link-claude"); p.add_argument("repo"); p.add_argument("--claude-home", default=str(Path.home() / ".claude")); p.set_defaults(fn=cmd_link_claude)
    args = parser.parse_args(argv)
    return args.fn(args)


